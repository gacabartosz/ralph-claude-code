#!/usr/bin/env bash
# tests/helpers/adapter_harness.bash - reusable scaffolding to validate agent
# provider adapters (multi-provider epic, #316 / MP.5).
#
# Every adapter implements the same contract, so every provider PR can be
# validated cheaply with the same three checks:
#   <build_fn>      prompt_file loop_context session_id  -> populates CLAUDE_CMD_ARGS
#   <normalize_fn>  output_file result_file              -> writes the normalized struct
#   <caps_record>   space-separated capability tokens (supports_*)
#
# These helpers are adapter-agnostic: pass the adapter's function names / record,
# so the harness drives the Claude reference adapter, a mock adapter, or any
# future provider identically. log to stderr so failures surface under bats.

# harness_assert_argv <build_fn> <prompt_file> <loop_ctx> <session_id> -- <expected...>
# Run the adapter's command-build function and assert CLAUDE_CMD_ARGS matches the
# expected argv exactly (length + every element).
harness_assert_argv() {
    local build_fn="$1" prompt="$2" ctx="$3" sess="$4"
    shift 4
    [ "${1:-}" = "--" ] && shift
    local -a expected=("$@")

    CLAUDE_CMD_ARGS=()
    "$build_fn" "$prompt" "$ctx" "$sess" || {
        echo "harness: build fn '$build_fn' returned non-zero" >&2
        return 1
    }
    [ "${#CLAUDE_CMD_ARGS[@]}" -eq "${#expected[@]}" ] || {
        echo "harness argv length: got ${#CLAUDE_CMD_ARGS[@]} (${CLAUDE_CMD_ARGS[*]}), want ${#expected[@]} (${expected[*]})" >&2
        return 1
    }
    local i
    for i in "${!expected[@]}"; do
        [ "${CLAUDE_CMD_ARGS[$i]}" = "${expected[$i]}" ] || {
            echo "harness argv[$i]: got '${CLAUDE_CMD_ARGS[$i]}', want '${expected[$i]}'" >&2
            return 1
        }
    done
    return 0
}

# harness_normalize <normalize_fn> <fixture_file> <result_file>
# Run the adapter's normalize function against a recorded raw provider-output
# fixture, writing the normalized internal struct to result_file.
harness_normalize() {
    local normalize_fn="$1" fixture="$2" result="$3"
    [ -f "$fixture" ] || { echo "harness: fixture not found: $fixture" >&2; return 1; }
    "$normalize_fn" "$fixture" "$result"
}

# harness_assert_field <result_file> <jq_filter> <expected>
# Assert a single normalized field equals the expected value.
harness_assert_field() {
    local result="$1" filter="$2" want="$3"
    local got
    got=$(jq -r "$filter" "$result" 2>/dev/null)
    [ "$got" = "$want" ] || {
        echo "harness field $filter: got '$got', want '$want'" >&2
        return 1
    }
}

# harness_assert_capabilities_wellformed <caps_record>
# A capability record must be non-empty and every token must be a supports_*
# flag — catches typos and malformed records in provider PRs.
harness_assert_capabilities_wellformed() {
    local caps="$1" c
    [ -n "$caps" ] || { echo "harness: capabilities record is empty" >&2; return 1; }
    for c in $caps; do
        case "$c" in
            supports_*) ;;
            *) echo "harness: malformed capability token: '$c'" >&2; return 1 ;;
        esac
    done
    return 0
}

# harness_make_mock_cli <path> <fixture_file>
# Create an executable stub that mimics a provider CLI: it sleeps >1s (per the
# e2e early-failure rule — a real CLI call is never instant, so an instant mock
# would mask timing-dependent bugs) and emits the canned fixture to stdout,
# ignoring its own arguments. Use for end-to-end adapter drive tests.
harness_make_mock_cli() {
    local path="$1" fixture="$2"
    cat > "$path" <<MOCK
#!/usr/bin/env bash
# Mock provider CLI (generated by harness_make_mock_cli). Emits canned output.
sleep 1.1
cat "$fixture"
MOCK
    chmod +x "$path"
}
